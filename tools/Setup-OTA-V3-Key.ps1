param(
    [ValidateSet("Production", "Test")]
    [string]$Channel = "Production",
    [switch]$SetGitHubSecret
)

$ErrorActionPreference = "Stop"
$repo = "bbasa21/ava-ESP32-S3-WROOM-N8R2"
$root = Split-Path -Parent $PSScriptRoot

if ($Channel -eq "Test") {
    $keyDirectory = Join-Path $HOME "AVA-OTA-V3-Test-Key"
    $privateKey = Join-Path $keyDirectory "ota-v3-test-private.pem"
    $publicKey = Join-Path $keyDirectory "ota-v3-test-public.pem"
    $publicHeader = Join-Path $root "include\Ava_OTA_V3_TestPublicKey.h"
    $secretName = "AVA_OTA_V3_TEST_SIGNING_PRIVATE_KEY"
    $configuredMacro = "AVA_OTA_V3_TEST_PUBLIC_KEY_CONFIGURED"
    $pemMacro = "AVA_OTA_V3_TEST_PUBLIC_KEY_PEM"
} else {
    $keyDirectory = Join-Path $HOME "AVA-OTA-V3-Key"
    $privateKey = Join-Path $keyDirectory "ota-v3-private.pem"
    $publicKey = Join-Path $keyDirectory "ota-v3-public.pem"
    $publicHeader = Join-Path $root "include\Ava_OTA_V3_PublicKey.h"
    $secretName = "AVA_OTA_SIGNING_PRIVATE_KEY"
    $configuredMacro = "AVA_OTA_V3_PUBLIC_KEY_CONFIGURED"
    $pemMacro = "AVA_OTA_V3_PUBLIC_KEY_PEM"
}

$openssl = (Get-Command "openssl.exe" -ErrorAction SilentlyContinue).Source
if (-not $openssl) {
    $gitOpenSSL = Join-Path $env:ProgramFiles "Git\usr\bin\openssl.exe"
    if (Test-Path $gitOpenSSL) { $openssl = $gitOpenSSL }
}
if (-not $openssl) {
    throw "OpenSSL was not found. Install Git for Windows or OpenSSL, then run this script again."
}
if (Test-Path $privateKey) {
    throw "A key already exists at $privateKey. Do not overwrite it."
}

New-Item -ItemType Directory -Force -Path $keyDirectory | Out-Null
& $openssl ecparam -name prime256v1 -genkey -noout -out $privateKey
if ($LASTEXITCODE -ne 0) { throw "Could not generate the P-256 private key." }
& $openssl pkey -in $privateKey -pubout -out $publicKey
if ($LASTEXITCODE -ne 0) { throw "Could not derive the public key." }

$publicPem = (Get-Content -Raw $publicKey).Trim()
$header = @"
#pragma once

// Generated by tools/Setup-OTA-V3-Key.ps1 for the $Channel channel.
// Public key only. The matching private key is kept outside this repository.
#define $configuredMacro 1
#define $pemMacro R"AVAKEY(
$publicPem
)AVAKEY"
"@
Set-Content -Path $publicHeader -Value $header -Encoding ASCII

Write-Host ""
Write-Host "$Channel P-256 keypair generated." -ForegroundColor Green
Write-Host "Private key (KEEP SECRET): $privateKey" -ForegroundColor Yellow
Write-Host "Public key header:        $publicHeader"
Write-Host "Actions secret name:      $secretName"
Write-Host "The private key was NOT added to Git."

if ($SetGitHubSecret) {
    if (-not (Get-Command "gh.exe" -ErrorAction SilentlyContinue)) {
        throw "GitHub CLI (gh) is required for -SetGitHubSecret."
    }
    gh auth status
    if ($LASTEXITCODE -ne 0) { throw "Authenticate GitHub CLI with: gh auth login" }
    Get-Content -Raw $privateKey | gh secret set $secretName --repo $repo
    if ($LASTEXITCODE -ne 0) { throw "Could not upload the GitHub Actions secret $secretName." }
    Write-Host "GitHub Actions secret $secretName configured." -ForegroundColor Green
}

Write-Host ""
Write-Host "Next: commit only the generated public-key header and push the feature branch."
Write-Host "Never commit $privateKey or $publicKey."
